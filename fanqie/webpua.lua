-- UTF-8 单字符解码：返回 (码位, 下一字节位置)。非法字节返回 nil。
local function utf8_codepoint(str, i)
    local b1 = str:byte(i)
    if not b1 then return nil, i end
    if b1 < 0x80 then
        return b1, i + 1
    elseif b1 >= 0xC2 and b1 <= 0xDF then
        local b2 = str:byte(i + 1)
        if not b2 then return nil, i end
        return (b1 - 0xC0) * 0x40 + (b2 - 0x80), i + 2
    elseif b1 >= 0xE0 and b1 <= 0xEF then
        local b2, b3 = str:byte(i + 1), str:byte(i + 2)
        if not b2 or not b3 then return nil, i end
        return (b1 - 0xE0) * 0x1000 + (b2 - 0x80) * 0x40 + (b3 - 0x80), i + 3
    elseif b1 >= 0xF0 and b1 <= 0xF4 then
        local b2, b3, b4 = str:byte(i + 1), str:byte(i + 2), str:byte(i + 3)
        if not b2 or not b3 or not b4 then return nil, i end
        return (b1 - 0xF0) * 0x40000 + (b2 - 0x80) * 0x1000 + (b3 - 0x80) * 0x40 + (b4 - 0x80), i + 4
    end
    return nil, i
end

--- 解码一段 PUA 混淆文本。非字符串原样返回 nil。
---@param s string
---@return string|nil
function M.decode(s)
    if type(s) ~= "string" or s == "" then return s end
    local out, i, n = {}, 1, #s
    while i <= n do
        local code, next_i = utf8_codepoint(s, i)
        if not code then
            out[#out + 1] = s:sub(i, i)
            i = i + 1
        else
            local ch = MAP[code]
            out[#out + 1] = ch or s:sub(i, next_i - 1)
            i = next_i
        end
    end
    return table.concat(out)
end

--- 文本里是否还有未映射的 PUA 码位（用于日志/统计，不改变解码结果）。
function M.has_unknown(s)
    if type(s) ~= "string" then return false end
    local i, n = 1, #s
    while i <= n do
        local code, next_i = utf8_codepoint(s, i)
        if not code then
            i = i + 1
        else
            if code >= 0xE000 and code <= 0xF8FF and not MAP[code] then
                return true
            end
            i = next_i
        end
    end
    return false
end

